function measureWord(word, size) {
  let w = 0;
  const gap = size * 0.06;
  for (let i = 0; i < word.length; i++) {
    const ch = word[i];
    if (ch === ".") {
      w += size * 0.26;
      continue;
    }
    w += glyphOf(ch).w * size;
    if (i < word.length - 1) w += gap;
  }
  return w;
}
function layoutMessage(text, size, maxWidth, cx, top) {
  const space = size * 0.34;
  const words = text.split(" ");
  const lines = [];
  let line = [];
  let width = 0;
  for (const word of words) {
    const ww = measureWord(word, size);
    const extra = line.length ? space : 0;
    if (line.length && width + extra + ww > maxWidth) {
      lines.push(line);
      line = [word];
      width = ww;
    } else {
      width += extra + ww;
      line.push(word);
    }
  }
  if (line.length) lines.push(line);
  const lineH = size * 1.28;
  const segs = [];
  lines.forEach((wordsInLine, li) => {
    const lineWidth = wordsInLine.reduce((sum, w) => sum + measureWord(w, size), 0) + space * Math.max(0, wordsInLine.length - 1);
    let x = cx - lineWidth / 2;
    const y = top + li * lineH;
    wordsInLine.forEach((word, wi) => {
      if (wi > 0) x += space;
      for (let i = 0; i < word.length; i++) {
        const ch = word[i];
        if (ch === ".") {
          segs.push({
            d: "",
            x0: x + size * 0.1,
            y0: y + size * 0.78,
            x1: x + size * 0.1,
            y1: y + size * 0.78,
            dot: true
          });
          x += size * 0.26;
          continue;
        }
        const g = glyphOf(ch);
        const scalePoint = (p) => [x + p[0] * size, y + p[1] * size];
        for (const stroke of g.strokes) {
          const pts = stroke.map(scalePoint);
          if (pts.length < 2) continue;
          segs.push({
            d: smooth(pts),
            x0: pts[0][0],
            y0: pts[0][1],
            x1: pts[pts.length - 1][0],
            y1: pts[pts.length - 1][1],
            dot: false
          });
        }
        for (const dot of g.dots ?? []) {
          const [dx, dy] = scalePoint(dot);
          segs.push({ d: "", x0: dx, y0: dy, x1: dx, y1: dy, dot: true });
        }
        x += g.w * size + size * 0.06;
      }
    });
  });
  return segs;
}
function withMoves(segs) {
  const out = [];
  let prev = null;
  for (const seg of segs) {
    if (prev) {
      const dist = Math.hypot(seg.x0 - prev.x, seg.y0 - prev.y);
      if (dist > 2) {
        out.push({
          d: "",
          x0: prev.x,
          y0: prev.y,
          x1: seg.x0,
          y1: seg.y0,
          dot: false,
          move: true
        });
      }
    }
    out.push(seg);
    prev = { x: seg.x1, y: seg.y1 };
  }
  return out;
}
