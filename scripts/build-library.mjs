// Parses data/library.txt (the Master Topic Library) into supabase/seed.sql.
// Run: npm run seed
// Safe to re-run: every insert uses "on conflict do nothing".
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const src = readFileSync('data/library.txt', 'utf8').split('\n');
const q = s => `'${String(s).replace(/'/g, "''")}'`;

const fields = new Map();
const subs = [];
const topics = [];
let sub = null;
let n = 0;

for (const raw of src) {
  const line = raw.trimEnd();
  let m;
  if ((m = line.match(/^(\d{2})\. ([A-Z][A-Z &/-]+)$/))) {
    fields.set(m[1], m[2].trim());
    sub = null;
    continue;
  }
  if ((m = line.match(/^(\d+)\.(\d+) (.+)$/))) {
    const fid = String(m[1]).padStart(2, '0');
    if (!fields.has(fid)) continue;
    sub = { id: `${Number(m[1])}.${m[2]}`, fid, name: m[3].trim() };
    subs.push(sub);
    n = 0;
    continue;
  }
  if (sub && (m = line.match(/^ {4}- (.+)$/))) {
    n++;
    topics.push({ id: `${sub.id}.${n}`, sub: sub.id, title: m[1].trim() });
  }
}

// Starting difficulty heuristic per subfield: first three beginner,
// last two advanced, the rest intermediate. Editable later in the database.
const bySub = {};
for (const t of topics) (bySub[t.sub] ??= []).push(t);
for (const list of Object.values(bySub)) {
  list.forEach((t, i) => {
    t.diff = i < 3 ? 'beginner' : i >= list.length - 2 ? 'advanced' : 'intermediate';
  });
}

// Cross-disciplinary links between fields. Bidirectional in the app.
const links = [
  ['01', '02'], ['01', '03'], ['01', '08'], ['01', '09'],
  ['02', '06'], ['02', '07'], ['02', '09'], ['03', '06'],
  ['04', '01'], ['04', '02'], ['04', '05'], ['04', '06'],
  ['05', '06'], ['06', '09'], ['07', '09'], ['08', '09'],
  ['11', '02'], ['11', '03'], ['11', '10'],
  ['12', '05'], ['12', '07'], ['12', '10'],
  ['13', '02'], ['13', '03'], ['13', '10'],
  ['14', '02'], ['14', '04'], ['14', '10'],
  ['15', '01'], ['15', '08'], ['15', '09'],
];

const sql = [
  '-- Generated by scripts/build-library.mjs. Paste into the Supabase SQL editor after schema.sql.',
  `insert into fields (id, name) values\n${[...fields].map(([id, nm]) => `(${q(id)}, ${q(nm)})`).join(',\n')}\non conflict (id) do nothing;`,
  `insert into subfields (id, field_id, name) values\n${subs.map(s => `(${q(s.id)}, ${q(s.fid)}, ${q(s.name)})`).join(',\n')}\non conflict (id) do nothing;`,
  `insert into topics (id, subfield_id, title, difficulty) values\n${topics.map(t => `(${q(t.id)}, ${q(t.sub)}, ${q(t.title)}, ${q(t.diff)})`).join(',\n')}\non conflict (id) do nothing;`,
  `insert into field_links (field_a, field_b) values\n${links.map(([a, b]) => `(${q(a)}, ${q(b)})`).join(',\n')}\non conflict do nothing;`,
].join('\n\n');

mkdirSync('supabase', { recursive: true });
writeFileSync('supabase/seed.sql', sql + '\n');
console.log(`fields: ${fields.size}  subfields: ${subs.length}  topics: ${topics.length}  links: ${links.length}`);
